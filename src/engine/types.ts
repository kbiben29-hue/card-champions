import type { Step } from './text'

export type Zone =
	| 'deck'
	| 'hand'
	| 'discard'
	| 'play' // player's allies / supports / upgrades (and attachments: host set)
	| 'identity'
	| 'engaged' // minions engaged with a player
	| 'dealt' // facedown encounter cards waiting to be revealed
	| 'encDeck'
	| 'encDiscard'
	| 'villain'
	| 'main'
	| 'side' // side schemes (and player side schemes)
	| 'env' // environments
	| 'attached' // encounter attachments (host set)
	| 'boost' // facedown boost cards on the active enemy
	| 'setAside'
	| 'removed'
	| 'victory'

export interface Inst {
	uid: number
	code: string
	/** player index, or -1 for encounter cards */
	owner: number
	/** who controls it now (player index), -1 for encounter-side cards */
	ctrl: number
	/** game area (0 in cooperative games; 0 or 1 in competitive) */
	area: number
	zone: Zone
	dmg: number
	thr: number
	/** all-purpose / "uses" counters */
	ctr: number
	ex: boolean
	stun: number
	conf: number
	tough: number
	host?: number
	/** temporary stat bonuses until the end of the phase */
	bonus?: { atk?: number; thw?: number; def?: number; sch?: number; shield?: number }
	/** abilities already used this round / phase (index) */
	used?: number[]
	/** for the main scheme: which side shows */
	flipped?: boolean
	/** a player card put into play facedown as a Drone minion */
	facedown?: boolean
}

export interface Player {
	id: number
	name: string
	area: number
	hero: string
	alter: string
	set: string
	form: 'hero' | 'alter'
	flippedThisRound: boolean
	ident: number
	deck: number[]
	hand: number[]
	discard: number[]
	out: boolean
	/** resources generated by Resource abilities, waiting to be spent */
	pool: string
	/** player has passed the turn this phase */
	done: boolean
	/** leader basic cards (competitive) */
	leaderCards: number[]
	/** set-aside nemesis cards */
	nemesis: number[]
}

export interface Area {
	id: number
	players: number[]
	first: number
	villainSeq: string[]
	vStage: number
	villain: number
	schemeSeq: string[]
	mStage: number
	main: number
	encDeck: number[]
	encDiscard: number[]
	expert: boolean
	result?: 'win' | 'lose'
	/** competitive: 'registration' | 'resistance' */
	side?: string
	/** the scenario this area plays against */
	scenario: string
}

/** Things waiting for an answer. `who` is the player who answers (hot-seat: whoever is on the device). */
export type Prompt = { who: number; text: string; card?: number } & (
	| { kind: 'mulligan' }
	| { kind: 'target'; options: number[]; skip?: boolean; why: string }
	| { kind: 'choose'; options: string[] }
	| { kind: 'defend'; attacker: number; options: number[] }
	| { kind: 'manual'; lines: string[] }
	| { kind: 'discardDown'; n: number }
	| { kind: 'window'; options: { uid: number; ab: number; label: string }[] }
	| { kind: 'searchPick'; options: number[] }
	| { kind: 'allyLimit' }
)

export interface Ctx {
	area: number
	player: number
	src: number
	that?: number
	/** the last step did something (for "If no …, this card gains surge") */
	did?: boolean
	/** for the encounter card being revealed */
	surge?: boolean
	cancelled?: boolean
	/** current attack (for prevent / attack riders) */
	attack?: number
}

export type Job =
	| { k: 'steps'; steps: Step[]; ctx: Ctx; i: number; pick?: number; picks?: number[] }
	| { k: 'villainPhase'; area: number; step: number; who?: number }
	| { k: 'activate'; area: number; enemy: number; target: number; mode: 'attack' | 'scheme'; step: number; boosts: number[]; extra: number; defender?: number; gains: string[]; prevent: number | 'all' | null; ctxSrc?: number; plus?: number }
	| { k: 'reveal'; area: number; player: number; uid: number; step: number; fromDeck: boolean; surge?: boolean; cancelled?: boolean }
	| { k: 'deal'; area: number }
	| { k: 'endRound' }
	| { k: 'playerTurn'; area: number; player: number }
	| { k: 'discardDown'; player: number }
	| { k: 'checkState' }

export interface LogLine {
	t: string
	p?: number
}

export interface Game {
	mode: 'coop' | 'pvp'
	/** "At the end of the phase/round, …" effects waiting to happen */
	later?: { when: 'phase' | 'round' | 'turn'; steps: Step[]; ctx: Ctx }[]
	insts: Record<number, Inst>
	next: number
	players: Player[]
	areas: Area[]
	phase: 'setup' | 'player' | 'villain' | 'over'
	/** whose turn it is (player phase) */
	active: number
	/** competitive: which area's phase it is */
	phaseArea: number
	round: number
	queue: Prompt[]
	jobs: Job[]
	log: LogLine[]
	rng: number
	winner?: string
	/** last visible event for the UI (banner) */
	banner?: string
	/** a card the UI should show big for a moment (encounter reveals) */
	spotlight?: number
}

export type Intent =
	| { t: 'mulligan'; player: number; cards: number[] }
	| { t: 'play'; player: number; uid: number; pay: number[]; target?: number }
	| { t: 'basic'; player: number; power: 'attack' | 'thwart' | 'recover'; target?: number }
	| { t: 'ally'; player: number; uid: number; power: 'attack' | 'thwart'; target?: number }
	| { t: 'ability'; player: number; uid: number; ab: number; pay?: number[]; target?: number }
	| { t: 'flip'; player: number }
	| { t: 'endTurn'; player: number; discard?: number[] }
	| { t: 'answer'; player: number; value: number | number[] | null }
	| { t: 'tool'; player: number; uid: number; op: ToolOp }
	| { t: 'draw'; player: number }
	| { t: 'concede'; player: number }

export type ToolOp =
	| 'dmg+'
	| 'dmg-'
	| 'thr+'
	| 'thr-'
	| 'ctr+'
	| 'ctr-'
	| 'exhaust'
	| 'ready'
	| 'stun'
	| 'conf'
	| 'tough'
	| 'discard'
	| 'hand'
	| 'defeat'
	| 'reveal'
